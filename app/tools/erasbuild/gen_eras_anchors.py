"""Generate the Go anchor table + golden test from the Python nid-dating model.

Reads analysis/anchors/nid_anchors.jsonl (the 281 verified creation-time
anchors) and writes:

  app/engine/internal/eras/anchors.go        — embedded anchor table
  app/engine/internal/eras/eras_golden_test.go — expectations computed by the
      PYTHON implementation (eras.estimate) for a fixed probe set, so the Go
      port is pinned to the Python source of truth by construction.

Run from the repo root:
    cd analysis && uv run python ../temp/gen_eras_anchors.py
"""
import datetime
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "analysis"))

from lib import eras  # noqa: E402

rows = [
    json.loads(line)
    for line in (ROOT / "analysis/anchors/nid_anchors.jsonl").read_text(
        encoding="utf-8"
    ).splitlines()
    if line.strip()
]
rows.sort(key=lambda r: int(r["nid"]))


def epoch_day(date_str: str) -> int:
    d = datetime.date.fromisoformat(date_str[:10])
    return (d - datetime.date(1970, 1, 1)).days


out = [
    "package eras",
    "",
    "// Code generated from analysis/anchors/nid_anchors.jsonl by",
    "// temp/gen_eras_anchors.py — DO NOT HAND-EDIT. day = days since",
    "// 1970-01-01 (UTC).",
    "var anchors = []anchor{",
]
for r in rows:
    d = r["addTime"][:10]
    out.append("\t{%d, %d}, // %s" % (int(r["nid"]), epoch_day(d), d))
out.append("}")

go_dir = ROOT / "app/engine/internal/eras"
go_dir.mkdir(parents=True, exist_ok=True)
(go_dir / "anchors.go").write_text("\n".join(out) + "\n", encoding="utf-8")

# Golden expectations from the Python source of truth. Probe set: anchor
# nids (exact tier), spread in-between nids (interpolation), and nids on
# both extrapolation sides.
probe = [2242, 2243, 5000, 48704, 100000, 200000, 300000, 400000, 500000,
         600000, 700000, 800000, 900000, 950000, 1000000, 1100000]
est = eras.estimate(probe)

t = [
    "package eras",
    "",
    'import "testing"',
    "",
    "// Code generated by temp/gen_eras_anchors.py — the expected values",
    "// were computed by the PYTHON implementation (analysis/lib/eras.py,",
    "// the source of truth), pinning the Go port by construction.",
    "func TestGoldenAgainstPython(t *testing.T) {",
    "\t golden := []Result{",
]
for _, row in est.iterrows():
    t.append(
        '\t\t{%s, "%s", %d, "%s", "%s"},'
        % (
            "true" if int(row["id"]) in {int(r["nid"]) for r in rows} else "false",
            row["est_date"].strftime("%Y-%m-%d"),
            int(row["est_year"]),
            row["mode"],
            row["confidence"],
        )
    )
t.append("\t }")
t.append("\t probe := []int64{%s}" % ", ".join(str(p) for p in probe))
t.append("\t for i, want := range golden {")
t.append("\t\t got := Estimate(probe[i])")
t.append("\t\t if got.EstDate != want.EstDate {")
t.append('\t\t\t t.Errorf("nid %d: est_date = %s, want %s", probe[i], got.EstDate, want.EstDate)')
t.append("\t\t }")
t.append("\t\t if got.EstYear != want.EstYear {")
t.append('\t\t\t t.Errorf("nid %d: est_year = %d, want %d", probe[i], got.EstYear, want.EstYear)')
t.append("\t\t }")
t.append("\t\t if got.Mode != want.Mode {")
t.append('\t\t\t t.Errorf("nid %d: mode = %s, want %s", probe[i], got.Mode, want.Mode)')
t.append("\t\t }")
t.append("\t\t if got.Confidence != want.Confidence {")
t.append('\t\t\t t.Errorf("nid %d: confidence = %s, want %s", probe[i], got.Confidence, want.Confidence)')
t.append("\t\t }")
t.append("\t }")
t.append("}")

(go_dir / "eras_golden_test.go").write_text("\n".join(t) + "\n", encoding="utf-8")
print("anchors:", len(rows), "| golden probes:", len(probe))
